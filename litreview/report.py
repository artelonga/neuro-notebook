"""Render REPORT.md from the data/ outputs (no network).

    python3 -m litreview.report
"""
from __future__ import annotations

import csv
import json
from collections import Counter

from .common import DATA, ROOT
from .literature import SOURCES
from .trials import REGISTRIES, TRIAL_TERMS

LICENSED = [
    ("Scopus", "Elsevier API (institutional key)",
     'TITLE-ABS-KEY(optogenet* OR "opto-genet*" OR optigenet*) AND TITLE-ABS-KEY(alzheimer* OR parkinson*)'),
    ("Web of Science Core Collection", "WoS Starter/Expanded API (Clarivate key)",
     'TS=(optogenet* OR "opto-genet*" OR optigenet*) AND TS=(alzheimer* OR parkinson*)'),
    ("Embase", "Ovid/Elsevier (licence; no open API)",
     "(optogenet* OR 'opto-genet*' OR optigenet*):ti,ab,kw AND (alzheimer* OR parkinson*):ti,ab,kw"),
    ("LILACS / BVS (pt/es)", "Web only (bot-protected; export CSV)",
     "(tw:(optogenet* OR optogenétic* OR optogenétic*)) AND (tw:(alzheimer* OR parkinson*))"),
    ("CNKI (zh)", "Web only (licence)", "SU=('光遗传'+'光遺傳') AND SU=('阿尔茨海默'+'帕金森')"),
    ("CiNii / J-STAGE (ja)", "CiNii OpenSearch API (free)", "光遺伝 OR オプトジェネティクス AND (アルツハイマー OR パーキンソン)"),
]


def table(rows, cols, header=None):
    out = ["| " + " | ".join(header or cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def main():
    log = json.loads((DATA / "search_log.json").read_text())
    counts = list(csv.DictReader((DATA / "counts.csv").open()))
    overlap = list(csv.reader((DATA / "overlap_matrix.csv").open()))
    works = list(csv.DictReader((DATA / "works.csv").open()))
    tlog = json.loads((DATA / "trials_log.json").read_text())
    trials = list(csv.DictReader((DATA / "trials.csv").open()))

    tot = counts[-1]
    n_rec, n_works = int(tot["retrieved"]), int(tot["works"])
    conf = [w for w in works if w["status"] == "confirmed"]
    multi = sum(1 for w in conf if int(w["n_versions"]) > 1)
    runs = sorted(v["run_at"] for v in log.values() if "run_at" in v)
    L = []
    L.append("# Optogenetics × Alzheimer/Parkinson — search report\n")
    L.append(f"_Generated by `python3 -m litreview.report`. Searches run {runs[0][:10]} "
             f"(last {runs[-1]}). Protocol: [PROTOCOL.md](PROTOCOL.md)._\n")

    # --- headline -------------------------------------------------------
    L.append("## Headline numbers\n")
    L.append(f"- **{n_rec}** records retrieved from **{len(log)}** programmatically queried databases")
    L.append(f"- **{n_works}** unique works after cross-database deduplication "
             f"({n_rec - n_works} duplicate records removed)")
    L.append(f"- **{tot['confirmed']} unique works meet the inclusion rule** (keyword re-check on "
             f"title/abstract/keywords); {tot['unverifiable']} unverifiable (no abstract) and "
             f"{tot['rejected']} rejected as search-engine false positives")
    inc = [t for t in trials if t["decision"] == "include"]
    inc_unique = [t for t in inc if not t["same_trial_as"]]
    inc_int = [t for t in inc_unique if t["category"].startswith("interventional:")]
    L.append(f"- Clinical-trial registries: **{len(trials)}** records → **{len(inc)}** about optogenetics → "
             f"**{len(inc_int)} distinct interventional optogenetic trials**, "
             f"**{sum(int(t['ad_pd_flag']) for t in inc)} in Alzheimer's or Parkinson's**\n")

    # --- AC -------------------------------------------------------------
    L.append("## Acceptance criteria\n")
    ok_dbs = [k for k, v in log.items() if v.get("status") == "ok"]
    L.append(table([
        {"ac": "AC-1", "what": "List of searchable databases, programmatic where possible",
         "st": f"✅ {len(ok_dbs)} literature DBs + {len(REGISTRIES)} trial registries queried by API; "
               f"{len(LICENSED)} licensed/web-only DBs documented with ready queries"},
        {"ac": "AC-2", "what": "Quantitative search, method explained (optogenetics AND (alzheimer OR parkinson), multilingual)",
         "st": "✅ exact query strings and hit counts per DB below and in `data/search_log.json`"},
        {"ac": "AC-3", "what": "Count per DB, unique-to-DB, total without duplicates, quick aggregation",
         "st": "✅ `data/counts.csv`, `data/overlap_matrix.csv`, `data/works.csv` (0/1 column per DB)"},
        {"ac": "AC-4", "what": "Systematic review of clinical-trial registries for any optogenetics use",
         "st": ("✅ " if all(isinstance(n, int) for v in tlog.values() for n in v["terms"].values())
                else "⚠️ partial: a registry failed at run time (see table; WHO ICTRP covers ChiCTR, JPRN, "
                     "ANZCTR, ReBEC, CTRI, DRKS) — rerun or export manually. ")
               + "Screening decisions in `data/trials.csv`"},
    ], ["ac", "what", "st"], ["AC", "Criterion", "Status"]))
    L.append("")

    # --- AC-2/3 results --------------------------------------------------
    L.append("## Literature: results per database\n")
    L.append("`hits` = count reported by the database API; `confirmed` = works whose title/abstract/"
             "keywords really contain both concepts; `unique` = confirmed works found **only** in that "
             "database; `share` = fraction of all confirmed unique works covered by that database.\n")
    L.append(table(counts, ["database", "api_hits", "retrieved", "confirmed", "unverifiable", "rejected",
                            "unique_confirmed", "share_of_total_confirmed"],
                   ["Database", "Hits", "Retrieved", "Confirmed", "Unverifiable", "Rejected", "Unique", "Share"]))
    L.append(f"\nPreprint and journal versions of the same study are counted as one work "
             f"({multi} confirmed works merge >1 DOI; see `n_versions`).\n")
    L.append("### Overlap matrix (confirmed works found in both databases)\n")
    hdr = overlap[0]
    L.append(table([dict(zip(hdr, r)) for r in overlap[1:]], hdr, [""] + hdr[1:]))
    L.append("")
    L.append("### Flow (PRISMA 2020 identification stage)\n")
    L.append("```")
    L.append(f"Records identified via databases           n = {n_rec}")
    for c in counts[:-1]:
        L.append(f"  {c['database']:<40} n = {c['retrieved']}")
    L.append(f"Duplicate records removed                  n = {n_rec - n_works}")
    L.append(f"Unique works screened (keyword re-check)   n = {n_works}")
    L.append(f"  excluded: concept absent from TI/AB/KW   n = {tot['rejected']}")
    L.append(f"  awaiting manual check: no abstract       n = {tot['unverifiable']}")
    L.append(f"Works meeting the search inclusion rule    n = {tot['confirmed']}")
    L.append("```\n")
    yrs = Counter(w["year"] for w in conf if w["year"])
    L.append("Confirmed works by year: " + ", ".join(f"{y}: {yrs[y]}" for y in sorted(yrs)) + "\n")

    L.append("### Exact queries executed\n")
    for k, v in log.items():
        L.append(f"**{v['database']}** — {v.get('status')}, run {v.get('run_at')}\n")
        L.append(f"```\n{v.get('query', v.get('error'))}\n```")
        for name, s in (v.get("sensitivity") or {}).items():
            if isinstance(s, dict) and "hits" in s:
                L.append(f"- sensitivity — {name}: `{s['query']}` → {s['hits']} hits")
        L.append("")
    L.append("### Databases not queried programmatically (licence / bot-protection)\n")
    L.append("Run these manually, export RIS/CSV into `data/manual/`, and add them to the merge (see README).\n")
    L.append(table([{"db": a, "acc": b, "q": f"`{c}`"} for a, b, c in LICENSED], ["db", "acc", "q"],
                   ["Database", "Access", "Query"]))
    L.append("")

    # --- article database & peer review ---------------------------------
    idx_path = DATA / "articles_index.csv"
    if idx_path.exists():
        idx = list(csv.DictReader(idx_path.open()))
        n, pr = len(idx), sum(int(r["peer_reviewed"]) for r in idx)
        L.append("## Article database and peer-review status\n")
        L.append(f"`articles/` holds one Markdown file per confirmed work ({n}): YAML front matter "
                 f"(title, DOI, authors, identifiers, PRISMA identification trail, empty screening "
                 f"fields) and the abstract as the body. Peer-reviewed works are in `articles/peer_reviewed/`, "
                 f"the rest directly in `articles/`. Index: `data/articles_index.csv`. "
                 f"{sum(int(r['has_abstract']) for r in idx)} have an abstract, "
                 f"{sum(1 for r in idx if r['doi'])} a DOI.\n")
        L.append(f"**{pr} of {n} works ({pr / n:.0%}) are peer reviewed** (`peer_reviewed: true`).\n")
        pr_types = {"journal-article", "review"}
        labels = {"journal-article": "Journal article", "review": "Review", "preprint": "Preprint",
                  "thesis": "Thesis / dissertation", "conference-abstract": "Meeting abstract (journal supplement)",
                  "conference-paper": "Conference paper", "unknown": "Unknown type",
                  "editorial-or-news": "Editorial / news / commentary", "book": "Book or chapter",
                  "other": "Other (dataset, report)"}
        L.append(table([{"t": labels.get(k, k), "n": v, "p": str(k in pr_types).lower()}
                        for k, v in Counter(r["document_type"] for r in idx).most_common()],
                       ["t", "n", "p"], ["Document type", "Works", "peer_reviewed"]))
        L.append("")
        L.append("How it is decided: no database records peer review, so it is inferred from publication "
                 "type and venue.\n")
        L.append("- The evidence is ranked PubMed > Europe PMC > DOAJ (lists only peer-reviewed journals) "
                 "> OpenAlex (looked up by DOI) > Semantic Scholar. The evidence used for each work is "
                 "stored in `peer_review_basis`.")
        L.append("- A work counts as peer reviewed if any version of it was published as a journal "
                 "article or review. A preprint merged with its published version is therefore `true`.")
        L.append("- Preprints are recognised by DOI prefix or server name (bioRxiv incl. `10.64898`, "
                 "medRxiv, Research Square, SSRN, …).")
        L.append("- Meeting abstracts are recognised by supplement DOIs and numbered titles such as "
                 "\"P1‐172: …\", because OpenAlex and Semantic Scholar often type them as articles.\n")
        L.append("Caveats:\n")
        L.append("- `true` is not a quality judgement; a few venues are questionable.")
        L.append("- Full IEEE/EMBC proceedings papers are usually refereed but are counted `false` here, "
                 "which is conservative.")
        L.append("- `unknown` works (mostly theses or foreign-language items without a DOI) are `false`.")
        L.append("- Title-based deduplication can miss garbled titles, e.g. \"Aβ\" written as \"Ab\" or "
                 "\"A b\". Check for these during screening.\n")

    # --- AC-4 ------------------------------------------------------------
    L.append("## Clinical-trial registries: any use of optogenetics\n")
    L.append("Search terms (each run separately, results unioned): " + ", ".join(f"`{t}`" for t in TRIAL_TERMS) + "\n")
    rows = []
    for k, v in tlog.items():
        ok = {t: n for t, n in v["terms"].items() if isinstance(n, int)}
        failed = [t for t, n in v["terms"].items() if not isinstance(n, int)]
        rows.append({"r": v["registry"], "h": ", ".join(f"{t}: {n}" for t, n in ok.items() if n) or "0",
                     "n": v.get("records", ""),
                     "i": sum(1 for t in trials if t["decision"] == "include" and t["registry"].split()[0] in v["registry"]),
                     "s": v["terms"][failed[0]][:60] if failed else "ok"})
    L.append(table(rows, ["r", "h", "n", "i", "s"], ["Registry", "Non-zero term hits", "Records", "Included", "Status"]))
    L.append("")
    cat = Counter(t["category"] for t in trials)
    L.append("Screening outcome (all registry records): " + ", ".join(f"{k}: {v}" for k, v in cat.most_common()) + "\n")
    L.append("### Included trials\n")
    L.append(table(inc, ["trial_id", "registry", "category", "phase", "status", "start", "sponsor", "conditions",
                         "same_trial_as", "reason"],
                   ["ID", "Registry", "Category", "Phase", "Status", "Start", "Sponsor", "Condition",
                    "Duplicate of", "Notes"]))
    L.append("")
    adpd = [t for t in inc if t["ad_pd_flag"] == "1"]
    L.append(f"**Alzheimer's / Parkinson's:** {len(adpd)} registered optogenetic trials. "
             "Every registered optogenetic intervention to date targets retinal disease "
             "(retinitis pigmentosa, Stargardt disease, geographic atrophy). For the review this means "
             "the AD/PD evidence base is entirely preclinical.\n")
    (ROOT / "REPORT.md").write_text("\n".join(L))
    print("wrote REPORT.md")


if __name__ == "__main__":
    main()
